JS = '''() => {
  const transb = document.documentElement.scrollWidth > window.innerWidth;
  const titulos = [...document.querySelectorAll('h1,h2,h3')].filter(t => t.offsetParent).map(t => {
    const cs = getComputedStyle(t);
    const lh = parseFloat(cs.lineHeight) || parseFloat(cs.fontSize) * 1.2;
    return {texto: t.innerText.slice(0, 60), linhas: Math.round(t.getBoundingClientRect().height / lh)};
  }).filter(t => t.linhas > 2);
  const largos = [...document.querySelectorAll('body *')].filter(e => e.getBoundingClientRect().right > window.innerWidth + 1 && e.offsetParent && !e.closest('dialog')).slice(0,5).map(e => e.tagName + '.' + e.className);
  return {transbordo: transb, largos, titulos_3_linhas: titulos,
          n_h1: document.querySelectorAll('h1').length};
}'''

