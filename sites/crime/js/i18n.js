let cur = 'en';
export function setLang(l) { cur = LANGS.includes(l) ? l : 'en'; document.documentElement.lang = cur === 'pt' ? 'pt-PT' : 'en'; }
export function lang() { return cur; }
export function t(key, vars) {
  let s = D[cur][key] ?? D.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}
export function list(key) { return D[cur][key] || D.en[key]; }
export function errText(code) { return D[cur].err[code] || D.en.err[code] || D[cur].err.default; }
export function guessLang() {
  try { const s = localStorage.getItem('cr.lang'); if (s) return s; } catch {}
  return (navigator.language || '').toLowerCase().startsWith('pt') ? 'pt' : 'en';
}
